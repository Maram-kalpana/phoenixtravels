    /**
     * Remove the specified resource from storage.
     */
    public function destroy(Request $request, $id){
         if ($request->ajax()){
            $course = CountryModel::findOrFail($id);
            if ($course){
                $course->delete();
                return response()->json(array('success' => true));
            }
        }
